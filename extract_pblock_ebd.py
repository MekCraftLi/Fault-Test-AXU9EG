#!/usr/bin/env python3
"""
extract_pblock_ebd.py
Faithfully replicates addr-shiyan's genXilinxFAR_2020.py flow for UltraScale+:
1. Identifies PBlock frame boundaries (min_frame .. max_frame) from top.ll.
2. Parses top.ebd (Essential Bits Data generated by Vivado) to extract authentic
   LUT/routing essential bits within the pblock_TESTMODULE frame bounds.
3. Formats addresses using UltraScale+ Linear Frame Address (LFA):
   val = ((linearAddr & 0xFFFFF) << 12) | ((wordAddr & 0x7F) << 5) | (bitOffset & 0x1F)
4. Selects a well-distributed set of 128 targets across the PBlock frames.
5. Outputs ebd.bin, frameRange.txt, and ebd_table.h.
"""

import os
import re
import struct

def main():
    base_dir = r"C:\Project\ZYNQ_test\Fault-Test-AXU9EG\fault-test-ps\bsp"
    ll_path = os.path.join(base_dir, "top.ll")
    ebd_path = os.path.join(base_dir, "top.ebd")
    ebd_bin_path = os.path.join(base_dir, "ebd.bin")
    frame_range_path = os.path.join(base_dir, "frameRange.txt")
    app_table_path = r"C:\Project\ZYNQ_test\Fault-Test-AXU9EG\fault-test-ps\application\ebd_table.h"

    words_per_frame = 93
    bits_per_frame = words_per_frame * 32

    # 1. Determine PBlock frame boundaries from top.ll
    pblock_slices = set()
    for x in range(48, 54):
        for y in range(140, 160):
            pblock_slices.add(f"SLICE_X{x}Y{y}")

    frame_indices = set()
    with open(ll_path, "r") as f:
        for line in f:
            if not line.startswith("Bit"):
                continue
            m = re.search(r"Block=(SLICE_X\d+Y\d+|DSP48E2_X\d+Y\d+)", line)
            if (m and m.group(1) in pblock_slices) or "TESTMODULE" in line:
                parts = line.split()
                bit_idx = int(parts[1])
                f_idx = bit_idx // bits_per_frame
                frame_indices.add(f_idx)

    min_frame = min(frame_indices)
    max_frame = max(frame_indices)
    print(f"[EBD Extraction] PBlock frame range from top.ll: {min_frame} (0x{min_frame:04X}) .. {max_frame} (0x{max_frame:04X})")

    # 2. Parse top.ebd (replicating addr-shiyan parseEBDfile)
    all_eb_targets = []
    with open(ebd_path, "r") as f:
        wordCnt = 0
        for line in f:
            line = line.strip()
            if len(line) == 32 and all(c in '01' for c in line):
                frame_idx = wordCnt // words_per_frame
                word_idx = wordCnt % words_per_frame
                if min_frame <= frame_idx <= max_frame:
                    for bitOffset in range(32):
                        if line[31 - bitOffset] == '1':
                            val = ((frame_idx & 0xFFFFF) << 12) | ((word_idx & 0x7F) << 5) | (bitOffset & 0x1F)
                            all_eb_targets.append((val, frame_idx, word_idx, bitOffset))
                elif frame_idx > max_frame:
                    break
                wordCnt += 1

    total_eb = len(all_eb_targets)
    print(f"[EBD Extraction] Found {total_eb} total essential bits inside pblock_TESTMODULE frames.")

    # 3. Select 128 well-distributed targets across the PBlock frames
    TARGET_COUNT = 128
    stride = total_eb // TARGET_COUNT
    selected = [all_eb_targets[i * stride] for i in range(TARGET_COUNT)]

    print(f"[EBD Extraction] Selected {len(selected)} distributed essential bit targets.")

    # 4. Generate ebd.bin matching addr-shiyan binary format
    with open(ebd_bin_path, "wb") as fb:
        for t in selected:
            fb.write(struct.pack("I", t[0]))

    # 5. Generate frameRange.txt
    with open(frame_range_path, "w") as ft:
        for t in selected:
            ft.write(f"0x{t[0]:08X}\n")

    # 6. Generate ebd_table.h for application
    with open(app_table_path, "w") as f:
        f.write("// Auto-generated PBlock Essential Bits Target Table strictly from top.ebd (UltraScale+ LFA)\n")
        f.write("#ifndef EBD_TABLE_H\n")
        f.write("#define EBD_TABLE_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"constexpr uint32_t PBLOCK_EBD_COUNT = {len(selected)};\n\n")
        f.write("struct PBlockTarget {\n")
        f.write("    uint32_t far;\n")
        f.write("};\n\n")
        f.write(f"static const PBlockTarget PBLOCK_EBD_TARGETS[PBLOCK_EBD_COUNT] = {{\n")
        for i in range(0, len(selected), 4):
            chunk = selected[i:i+4]
            items = [f"{{0x{t[0]:08X}U}}" for t in chunk]
            line = "    " + ", ".join(items) + ("," if i+4 < len(selected) else "") + "\n"
            f.write(line)
        f.write("};\n\n")
        f.write("#endif // EBD_TABLE_H\n")

    print(f"[EBD Extraction] Successfully generated {ebd_bin_path} ({len(selected) * 4} bytes).")
    print(f"[EBD Extraction] Successfully generated {frame_range_path} ({len(selected)} entries).")
    print(f"[EBD Extraction] Successfully generated {app_table_path}.")

if __name__ == "__main__":
    main()
