#!/usr/bin/env python3
"""
generate_broad_pblock_targets.py
Extracts 512 authentic fault injection targets uniformly sampled across
all 97,789 essential configuration bits in pblock_TESTMODULE:
- Linear Frame Range: 17039 - 17406 (covering all 124 CLB/DSP tiles in CLOCK_REGION X1Y2)
- Extracted directly from top.ebd (essential bits generated by Vivado bitstream)
- Format: val = (linear_frame << 12) | (word_idx << 5) | bit_idx
"""

import os
import struct

def main():
    base_dir = r"C:\Project\ZYNQ_test\Fault-Test-AXU9EG\fault-test-ps\bsp"
    ebd_path = os.path.join(base_dir, "top.ebd")
    ebd_bin_path = os.path.join(base_dir, "ebd.bin")
    frame_range_path = os.path.join(base_dir, "frameRange.txt")
    app_table_path = r"C:\Project\ZYNQ_test\Fault-Test-AXU9EG\fault-test-ps\application\ebd_table.h"

    pblock_frames = set(range(17039, 17199)) | set(range(17219, 17407))

    all_targets = []
    with open(ebd_path, "r") as f:
        wordCnt = 0
        for line in f:
            line = line.strip()
            if len(line) == 32 and all(c in '01' for c in line):
                f_idx = wordCnt // 93
                w_idx = wordCnt % 93
                if f_idx in pblock_frames:
                    for b_idx in range(32):
                        if line[31 - b_idx] == '1':
                            val = ((f_idx & 0xFFFFF) << 12) | ((w_idx & 0x7F) << 5) | (b_idx & 0x1F)
                            all_targets.append((val, f_idx, w_idx, b_idx))
                elif f_idx > max(pblock_frames):
                    break
                wordCnt += 1

    print(f"[Targets] Total essential bits extracted in pblock: {len(all_targets)}")

    NUM_TARGETS = 512
    stride = len(all_targets) // NUM_TARGETS
    sampled = [all_targets[i * stride] for i in range(NUM_TARGETS)]

    # Write ebd.bin
    with open(ebd_bin_path, "wb") as fb:
        for t in sampled:
            fb.write(struct.pack("I", t[0]))

    # Write frameRange.txt
    with open(frame_range_path, "w") as ft:
        for t in sampled:
            ft.write(f"0x{t[0]:08X}\n")

    # Write ebd_table.h
    with open(app_table_path, "w") as f:
        f.write("// Auto-generated Authentic PBlock Fault Injection Targets (Broad PBlock Coverage 512)\n")
        f.write(f"// Uniformly sampled from all {len(all_targets)} essential bits across {len(pblock_frames)} frames\n")
        f.write("#ifndef EBD_TABLE_H\n")
        f.write("#define EBD_TABLE_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"constexpr uint32_t PBLOCK_EBD_COUNT = {len(sampled)};\n\n")
        f.write("struct PBlockTarget {\n")
        f.write("    uint32_t far;\n")
        f.write("    uint16_t frame;\n")
        f.write("    uint8_t  word;\n")
        f.write("    uint8_t  bit;\n")
        f.write("};\n\n")
        f.write(f"static const PBlockTarget PBLOCK_EBD_TARGETS[PBLOCK_EBD_COUNT] = {{\n")
        for t in sampled:
            f.write(f"    {{0x{t[0]:08X}U, {t[1]}, {t[2]}, {t[3]}}},\n")
        f.write("};\n\n")
        f.write("#endif // EBD_TABLE_H\n")

    frames_covered = len(set(t[1] for t in sampled))
    print(f"[Targets] Successfully wrote {len(sampled)} targets covering {frames_covered} distinct frames!")

if __name__ == "__main__":
    main()
